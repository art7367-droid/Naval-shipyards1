// Функции для работы с базой данных
export function getShipById(id: string): Ship | undefined {
  return shipsDatabase.find(ship => ship.id === id);
}

export function getShipsByType(type: ShipType): Ship[] {
  return shipsDatabase.filter(ship => ship.type === type);
}

export function getShipsByProgram(program: string): Ship[] {
  return shipsDatabase.filter(ship => ship.program === program);
}

export function getShipsByYard(yard: string): Ship[] {
  return shipsDatabase.filter(ship => ship.historicalYard === yard);
}

export function searchShips(query: string): Ship[] {
  const lowerQuery = query.toLowerCase();
  return shipsDatabase.filter(ship => 
    ship.name.toLowerCase().includes(lowerQuery) ||
    ship.nameJp.includes(query) ||
    ship.class.toLowerCase().includes(lowerQuery) ||
    ship.description.toLowerCase().includes(lowerQuery)
  );
}

export function getTotalCost(ships: Ship[]): number {
  return ships.reduce((sum, ship) => sum + ship.cost, 0);
}

export function getTotalDisplacement(ships: Ship[]): number {
  return ships.reduce((sum, ship) => sum + ship.displacement, 0);
}
